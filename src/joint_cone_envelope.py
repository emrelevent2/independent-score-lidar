"""Same coupled-null family, tighter query relaxation of an eta interval.

For fixed geometry and eta in [l,u], the query pulse is exactly a positive
cone generated by g+l*shift(g) and g+u*shift(g). Keeping those TWO columns
avoids choosing a different eta in every temporal bin. Calibration still
couples eta by subdivision; all bounds cover the same physical family.
"""
import heapq
import numpy as np
from flint import arb
from joint_calibration_envelope import Cell
from joint_calibration_model import query_basis
from envelope_evidence import _observations,outward_float
from linear_envelope_profile import profile_upper


def query_cone_basis(bins,d0,d1,w0,w1,e0,e1):
    low0,high0=query_basis(bins,d0,d1,w0,w1,e0,e0)
    low1,high1=query_basis(bins,d0,d1,w0,w1,e1,e1)
    return np.column_stack([low0[:,0],low1[:,0],low0[:,1]]),np.column_stack([high0[:,0],high1[:,0],high0[:,1]])


def cone_shared_cover(query,calibration_provider,query_cycles=1000,cap=.25,
                      initial_eta=8,initial_delay=16,max_boxes=1024,
                      decision_level=None):
    query=np.asarray(query)
    if not(0<cap<=.25 and initial_eta>=1 and initial_delay>=1 and max_boxes>=initial_eta*initial_delay):raise ValueError('Invalid cone-cover budget')
    _,_,_,saturated=_observations(query,query_cycles,'first')
    cache={};queue=[];counter=profiles=fallbacks=optimizer_failures=pruned=0
    def cal_upper(e0,e1):
        nonlocal fallbacks,optimizer_failures
        key=(e0,e1)
        if key not in cache:
            fit=calibration_provider(e0,e1);cache[key]=fit
            fallbacks+=not fit.get('profile_certified',fit.get('tangent_certified',False));optimizer_failures+=fit.get('optimizer_success') is False
        return cache[key]['upper']
    def add(e0,e1,d0,d1,w0,w1,parent=None):
        nonlocal counter,profiles,fallbacks,optimizer_failures,pruned
        cu=cal_upper(e0,e1);upper=outward_float(arb(cu)+arb(saturated))
        if decision_level is not None and upper<=decision_level:pruned+=1
        else:
            lo,hi=query_cone_basis(len(query),d0,d1,w0,w1,e0,e1)
            a=max(float(query.sum())*.35,1.)/(5*1.0645);b=max(float(query.sum())*.3,1.)
            fit=profile_upper(query,lo,hi,query_cycles,[a,a,b]);profiles+=1
            upper=outward_float(arb(cu)+arb(fit['upper']));fallbacks+=not fit['tangent_certified'];optimizer_failures+=not fit['optimizer_success']
        if parent is not None:upper=min(upper,parent)
        counter+=1;c=Cell(e0,e1,d0,d1,w0,w1,upper);heapq.heappush(queue,(-upper,counter,c))
    etas=np.linspace(0.,cap,initial_eta+1);delays=np.linspace(0.,len(query)-1.,initial_delay+1)
    for e0,e1 in zip(etas[:-1],etas[1:]):
        for d0,d1 in zip(delays[:-1],delays[1:]):add(float(e0),float(e1),float(d0),float(d1),4.5,5.5)
    while queue and counter+2<=max_boxes:
        if decision_level is not None and -queue[0][0]<=decision_level:break
        _,_,c=heapq.heappop(queue);mean=(c.w0+c.w1)/2
        spans=[(c.eta1-c.eta0)/(cap/16),(c.d1-c.d0)/mean,3*(c.w1-c.w0)/mean];axis=int(np.argmax(spans))
        if axis==0:
            mid=(c.eta0+c.eta1)/2
            if mid in (c.eta0,c.eta1):heapq.heappush(queue,(-c.upper,counter,c));break
            add(c.eta0,mid,c.d0,c.d1,c.w0,c.w1,c.upper);add(mid,c.eta1,c.d0,c.d1,c.w0,c.w1,c.upper)
        elif axis==1:
            mid=(c.d0+c.d1)/2
            if mid in (c.d0,c.d1):heapq.heappush(queue,(-c.upper,counter,c));break
            add(c.eta0,c.eta1,c.d0,mid,c.w0,c.w1,c.upper);add(c.eta0,c.eta1,mid,c.d1,c.w0,c.w1,c.upper)
        else:
            mid=(c.w0+c.w1)/2
            if mid in (c.w0,c.w1):heapq.heappush(queue,(-c.upper,counter,c));break
            add(c.eta0,c.eta1,c.d0,c.d1,c.w0,mid,c.upper);add(c.eta0,c.eta1,c.d0,c.d1,mid,c.w1,c.upper)
    if not queue:raise ArithmeticError('Complete cone cover unexpectedly empty')
    return dict(upper=-queue[0][0],boxes_evaluated=counter,query_profiles=profiles,
        calibration_profiles=len(cache),calibration_pruned_query_profiles=pruned,
        conservative_fallbacks=fallbacks,optimizer_failures=optimizer_failures,shared_eta_range=[0.,cap],
        query_parameterization='two eta-endpoint pulse columns and nonnegative background',
        scope='Complete eta/delay/width cover of the same confidence-box-coupled null,with a tighter query relaxation')
